/**
 * The edited fields {@link BaseApplicationDetails} hands `onUpdate`. Whether the client is public does
 * not change.
 */
export type ApplicationUpdateSubmission = Omit<ApplicationSubmission, 'publicClient'>;

/**
 * What {@link BaseApplicationDetails} hands its `children` render function, so the application can be
 * shown with any UI.
 */
export interface BaseApplicationDetailsRenderProps {
  application?: Application;
  /**
   * The new client secret, to show once. `null` while there is none.
   */
  clientSecret: string | null;
  error: string | null;
  isDeleting: boolean;
  isLoading: boolean;
  isRegeneratingSecret: boolean;
  isRunningLifecycleAction: boolean;
  isUpdating: boolean;
  /**
   * The account lifecycle actions offered for the application. Empty when none is allowed.
   */
  lifecycleActions: AccountLifecycleAction[];
  /**
   * The application's OAuth configuration, without its client secret. Undefined when it has no OAuth client.
   */
  oauth?: Omit<OAuth2Config, 'clientSecret'>;
  /**
   * Deletes the application. Undefined when deletion is not allowed, including for read-only applications.
   */
  onDelete?: () => void;
  /**
   * Runs an account lifecycle action. Undefined when none is allowed.
   */
  onLifecycleAction?: (action: AccountLifecycleAction, operatorNote?: string) => void;
  /**
   * Gives the application a new client secret. Undefined when not allowed, for read-only applications
   * and for applications without a confidential OAuth client.
   */
  onRegenerateSecret?: () => void;
  /**
   * Hides the new client secret once it has been copied. Undefined while there is no secret.
   */
  onSecretDismiss?: () => void;
  /**
   * Saves edited fields. Undefined when editing is not allowed, including for read-only applications.
   */
  onUpdate?: (application: ApplicationUpdateSubmission) => void;
}

export interface BaseApplicationDetailsProps {
  /**
   * Controls rendered next to the application's name.
   */
  actions?: ReactNode;
  application?: Application;
  /**
   * Renders custom UI in place of the default view. Receives the application, its OAuth configuration,
   * the loading and error state, the actions the app allows and the new client secret to show.
   */
  children?: (props: BaseApplicationDetailsRenderProps) => ReactNode;
  className?: string;
  /**
   * A client secret just generated by `onRegenerateSecret`, shown once until `onSecretDismiss` clears it.
   */
  clientSecret?: string | null;
  error?: string | null;
  isDeleting?: boolean;
  isLoading?: boolean;
  isRegeneratingSecret?: boolean;
  isRunningLifecycleAction?: boolean;
  isUpdating?: boolean;
  /**
   * The account lifecycle actions to offer (suspend, unsuspend; applications are never locked), shown only with `onLifecycleAction`. They change
   * only runtime state, so they apply to read-only applications too.
   */
  lifecycleActions?: AccountLifecycleAction[];
  /**
   * Deletes the application. The delete action is hidden when omitted.
   */
  onDelete?: () => void;
  /**
   * Runs an account lifecycle action. Suspending and unsuspending ask for confirmation first.
   */
  onLifecycleAction?: (action: AccountLifecycleAction, operatorNote?: string) => void;
  /**
   * Gives the application a new client secret. The regenerate action is hidden when omitted, and for
   * public clients, which have no secret.
   */
  onRegenerateSecret?: () => void;
  /**
   * Called when the user has copied the new client secret.
   */
  onSecretDismiss?: () => void;
  /**
   * Saves the edited general fields, redirect URIs and grant types. Editing is offered only when set.
   */
  onUpdate?: (application: ApplicationUpdateSubmission) => void;
  preferences?: Preferences;
}

const toFormValues = (application: Application, oauth?: OAuth2Config): ApplicationFormValues => ({
  description: application.description ?? '',
  grantTypes: oauth?.grantTypes ?? [],
  logoUrl: application.logoUrl ?? '',
  name: application.name,
  publicClient: Boolean(oauth?.publicClient),
  redirectUris: (oauth?.redirectUris ?? []).join(', '),
  url: application.url ?? '',
});

const toSubmission = (values: ApplicationFormValues): ApplicationSubmission => ({
  description: values.description.trim() || undefined,
  grantTypes: values.grantTypes,
  logoUrl: values.logoUrl.trim() || undefined,
  name: values.name.trim(),
  publicClient: values.publicClient,
  redirectUris: parseRedirectUris(values.redirectUris),
  url: values.url.trim() || undefined,
});

/**
 * Shows an application's general fields and OAuth configuration. Holds no data of its own: pass the
 * application and handle editing, deletion and client secret regeneration, each offered only when its
 * handler is set.
 */
const BaseApplicationDetails: FC<BaseApplicationDetailsProps> = ({
  actions,
  application,
  children,
  className,
  clientSecret = null,
  error = null,
  isDeleting = false,
  isLoading = false,
  isRegeneratingSecret = false,
  isRunningLifecycleAction = false,
  isUpdating = false,
  lifecycleActions = [],
  onDelete,
  onLifecycleAction,
  onRegenerateSecret,
  onSecretDismiss,
  onUpdate,
  preferences,
}: BaseApplicationDetailsProps): ReactElement => {
  const {t} = useTranslation(preferences?.i18n);
  const styles: Record<string, string> = useAdminPartStyles();
  const [draft, setDraft] = useState<ApplicationFormValues | null>(null);

  const oauthConfig: OAuth2Config | undefined = getApplicationOAuthConfig(application);
  const isWritable: boolean = Boolean(application) && !application?.isReadOnly;
  const canRegenerate: boolean = isWritable && Boolean(oauthConfig) && !oauthConfig?.publicClient;

  if (children) {
    let oauth: Omit<OAuth2Config, 'clientSecret'> | undefined;

    if (oauthConfig) {
      const {clientSecret: storedSecret, ...rest}: OAuth2Config = oauthConfig;
      void storedSecret;
      oauth = rest;
    }

    return (
      <div className={className}>
        {children({
          application,
          clientSecret,
          error,
          isDeleting,
          isLoading,
          isRegeneratingSecret,
          isRunningLifecycleAction,
          isUpdating,
          lifecycleActions: onLifecycleAction && application ? lifecycleActions : [],
          oauth,
          onDelete: isWritable ? onDelete : undefined,
          onLifecycleAction: application ? onLifecycleAction : undefined,
          onRegenerateSecret: canRegenerate ? onRegenerateSecret : undefined,
          onSecretDismiss: clientSecret ? onSecretDismiss : undefined,
          onUpdate: isWritable ? onUpdate : undefined,
        })}
      </div>
    );
  }

  if (isLoading && !application) {
    return (
      <AdminSection block="application-details" className={className} preferences={preferences}>
        <span className={styles['muted']} role="status">
          <Spinner size="small" /> {t('admin.common.loading')}
        </span>
      </AdminSection>
    );
  }

  if (!application) {
    return (
      <AdminSection block="application-details" className={className} preferences={preferences}>
        <Alert variant="error" role="alert">
          {error ?? t('admin.common.errors.not_found')}
        </Alert>
      </AdminSection>
    );
  }

  const notSet: string = t('admin.applications.details.not_set');
  const overview: DetailListItem[] = [
    {
      label: t('admin.applications.list.columns.client_id'),
      value: oauthConfig?.clientId ? <CopyableText value={oauthConfig.clientId} /> : notSet,
    },
    {label: t('admin.applications.details.type'), value: application.type ?? application.template ?? notSet},
    {label: t('admin.common.columns.organization_unit'), value: application.ouId ?? notSet},
    {label: t('admin.applications.fields.url'), value: application.url ?? notSet},
    {label: t('admin.applications.fields.logo_url'), value: application.logoUrl ?? notSet},
  ];

  if (application.status?.value) {
    overview.push({
      label: t('admin.common.columns.status'),
      value: <AccessStatusBadge status={application.status.value} />,
    });
  }

  const handleSave = (event: FormEvent<HTMLFormElement>): void => {
    event.preventDefault();

    if (!draft) {
      return;
    }

    const {publicClient, ...submission}: ApplicationSubmission = toSubmission(draft);
    void publicClient;
    onUpdate?.(submission);
    setDraft(null);
  };

  return (
    <AdminSection
      block="application-details"
      className={className}
      title={application.name}
      description={application.description}
      preferences={preferences}
      actions={
        <>
          {actions}
          {onLifecycleAction && (
            <AccountLifecycleButtons
              actions={lifecycleActions}
              isRunning={isRunningLifecycleAction}
              name={application.name}
              onAction={onLifecycleAction}
            />
          )}
          {onDelete && isWritable && (
            <ConfirmButton
              confirmText={t('admin.applications.details.delete.confirm', {name: application.name})}
              isLoading={isDeleting}
              onConfirm={onDelete}
            >
              {t('admin.applications.details.delete.action')}
            </ConfirmButton>
          )}
        </>
      }
    >
      {error && (
        <Alert variant="error" role="alert">
          {error}
        </Alert>
      )}
      {draft ? (
        <Panel title={t('admin.applications.details.edit.action')}>
          <form
            className={styles['row']}
            style={{alignItems: 'stretch', flexDirection: 'column'}}
            onSubmit={handleSave}
            noValidate
          >
            <ApplicationFormFields
              preferences={preferences}
              values={draft}
              onInputChange={(field: ApplicationTextField, value: string): void =>
                setDraft((previous: ApplicationFormValues | null) => previous && {...previous, [field]: value})
              }
              onGrantTypesChange={(grantTypes: string[]): void =>
                setDraft((previous: ApplicationFormValues | null) => previous && {...previous, grantTypes})
              }
            />
            <div className={styles['row']} style={{justifyContent: 'flex-end'}}>
              <Button type="button" variant="text" disabled={isUpdating} onClick={(): void => setDraft(null)}>
                {t('admin.common.actions.cancel')}
              </Button>
              <Button
                type="submit"
                loading={isUpdating}
                disabled={isUpdating || !isApplicationSubmissionValid(toSubmission(draft))}
              >
                {t('admin.applications.details.edit.save')}
              </Button>
            </div>
          </form>
        </Panel>
      ) : (
        <>
          <Panel
            title={t('admin.applications.details.overview')}
            actions={
              onUpdate && isWritable ? (
                <Button
                  variant="outline"
                  size="small"
                  onClick={(): void => setDraft(toFormValues(application, oauthConfig))}
                >
                  {t('admin.applications.details.edit.action')}
                </Button>
              ) : undefined
            }
          >
            <DetailList items={overview} />
          </Panel>
          {oauthConfig && (
            <Panel
              title={t('admin.applications.details.oauth')}
              actions={
                onRegenerateSecret && canRegenerate && !clientSecret ? (
                  <ConfirmButton
                    confirmText={t('admin.applications.details.secret.confirm', {name: application.name})}
                    isLoading={isRegeneratingSecret}
                    onConfirm={onRegenerateSecret}
                  >
                    {t('admin.applications.details.secret.action')}
                  </ConfirmButton>
                ) : undefined
              }
            >
              {clientSecret && (
                <ClientSecretNotice secret={clientSecret} onDismiss={onSecretDismiss} preferences={preferences} />
              )}
              <DetailList
                items={[
                  {
                    label: t('admin.applications.fields.grant_types'),
                    value: (
                      <ChipList
                        label={t('admin.applications.fields.grant_types')}
                        emptyText={t('admin.applications.details.no_grant_types')}
                        items={(oauthConfig.grantTypes ?? []).map((grantType: string) => ({
                          id: grantType,
                          label: APPLICATION_GRANT_TYPES.includes(grantType)
                            ? t(`admin.applications.grant_types.${grantType}`)
                            : grantType,
                        }))}
                      />
                    ),
                  },
                  {
                    label: t('admin.applications.fields.redirect_uris'),
                    value: (
                      <ChipList
                        label={t('admin.applications.fields.redirect_uris')}
                        emptyText={t('admin.applications.details.no_redirect_uris')}
                        items={(oauthConfig.redirectUris ?? []).map((uri: string) => ({id: uri, label: uri}))}
                      />
                    ),
                  },
                  {
                    label: t('admin.applications.details.public_client'),
                    value: oauthConfig.publicClient
                      ? t('admin.applications.details.yes')
                      : t('admin.applications.details.no'),
                  },
                ]}
              />
            </Panel>
          )}
        </>
      )}
    </AdminSection>
  );
};

export default BaseApplicationDetails;
